const vm=require('node:vm'),fs=require('node:fs'),assert=require('node:assert/strict');
const context=vm.createContext({document:{addEventListener(){}},console,Intl,Date,Number,String,Array,Object,Math,Set,TextEncoder,crypto:require('node:crypto').webcrypto});
for(const file of ['catalog.js','attendance.js','app.js']){
 let source=fs.readFileSync('dist/'+file,'utf8');
 if(file==='app.js')source=source.replace(/render\(\);\s*$/,'');
 vm.runInContext(source,context);
}
vm.runInContext('render=()=>{};toast=()=>{};error=()=>{};',context);
const run=source=>vm.runInContext(source,context);
assert.equal(run('state.employees.length'),1);
assert.equal(run('state.customers.length'),1);
assert.equal(run('state.jobs.length'),1);
assert.equal(run('state.attendance.length+state.requests.length+state.invoices.length'),0);
assert.equal(run('state.inventory.length'),203);
assert.equal(run('state.inventory.every(p=>p.stock===0&&p.price===0)'),true);
assert.ok(run('Object.values(CARS).flat().length')>400);
run("session={admin:true};role='employee';requestCheckinOrCheckout()");
assert.equal(run('pendingAttendance().length'),1);
assert.equal(run("attendanceSummary('e1').Present"),0);
run('requestCheckinOrCheckout()');
assert.equal(run('state.attendance.length'),1,'duplicate check-ins blocked');
run("decideAttendance(state.attendance[0].id,'Present')");
assert.equal(run('state.attendance[0].status'),'Pending','employees cannot approve');
run("role='employer';decideAttendance(state.attendance[0].id,'Rejected')");
assert.equal(run("attendanceSummary('e1').Present"),0);
run("role='employee';requestCheckinOrCheckout();role='employer';decideAttendance(state.attendance[0].id,'Present')");
assert.equal(run("attendanceSummary('e1').Present"),1);
run("role='employee';requestCheckinOrCheckout()");
assert.ok(run('state.attendance[0].out'));
assert.equal(run("attendanceSummary('e1').Present"),1,'checkout retains attendance');
run("role='employer';saveAttendanceForm({employee:'e1',date:today,status:'Leave',note:''})");
assert.equal(run("attendanceSummary('e1').Present"),0);
assert.equal(run("attendanceSummary('e1').Leave"),1);
run("saveAttendanceForm({employee:'e1',date:today,status:'LOP',note:''})");
assert.equal(run("attendanceSummary('e1').LOP"),1);
run("saveAttendanceForm({employee:'all',date:today,status:'Holiday',note:''})");
assert.equal(run("attendanceSummary('e1').Holiday"),1);
assert.equal(run("saveAttendanceForm({employee:'all',date:today,status:'Present',in:'09:00'})"),false);
assert.equal(run("saveAttendanceForm({employee:'e1',date:'2099-01-01',status:'Present',in:'09:00'})"),false);
assert.equal(run("state.attendance.length"),1,'same-day statuses do not duplicate');
console.log('PASS: seed data, full catalogs, zero stock, approval/rejection, duplicate prevention, role checks, checkout, leave/LOP/holiday and future-date validation.');
